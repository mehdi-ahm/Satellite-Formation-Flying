function dxdt = nmpc_orbit_state(x,u,p)
% NMPC_ORBIT_STATE
%
% Exact implementation of Fanebust Eq. (3.23)-(3.24)
%
% State:
% x(1) = delta_a
% x(2) = delta_lambda
% x(3) = delta_e_x
% x(4) = delta_e_y
% x(5) = delta_i_x
% x(6) = delta_i_y
%
% Inputs:
% u(1) = beta_l   leader ballistic coefficient
% u(2) = beta_f   follower ballistic coefficient
%
% Parameters:
% p(1) = a_f
% p(2) = e_f
% p(3) = i_f
% p(4) = omega_f
% p(5) = rho_f
%
% Units:
% a_f     [m]
% angles  [rad]
% rho     [kg/m^3]
% beta    [m^2/kg]

%% ============================================================
% Constants
% ============================================================

G          = 6.6743e-11;       % [m^3 kg^-1 s^-2]
earth_mass = 5.972e24;         % [kg]

mu = G*earth_mass;             % [m^3/s^2]

J2 = 1.08263e-3;

R_E = 6371e3;                  % [m]


%% ============================================================
% Follower absolute orbital parameters
% ============================================================

a_f     = p(1);
e_f     = p(2);
i_f     = p(3);
omega_f = p(4);
rho_f   = p(5);


%% ============================================================
% NMPC inputs
% ============================================================

beta_l = u(1);
beta_f = u(2);


%% ============================================================
% Fanebust Eq. (3.24)
% ============================================================

A = (3/2) * sqrt( ((1 + x(1))^7 * mu) / a_f^7 );

I = 3 + 5*cos(2*(i_f - x(5)));

J_star = J2 * R_E^2;

E = sqrt( e_f^2 + x(3)^2 + x(4)^2 - 2*e_f*( x(3)*cos(omega_f) + x(4)*sin(omega_f) ) );


%% ============================================================
% Drag terms
% ============================================================

% Fanebust model uses f(e_f) in both terms

drag_l = beta_l * f_drag(e_f) * rho_f;

drag_f = beta_f * f_drag(e_f) * rho_f;


%% ============================================================
% State derivative
% Fanebust Eq. (3.23)
% ============================================================

dxdt = zeros(6,1);


% ------------------------------------------------------------
% 1) delta_a_dot
% ------------------------------------------------------------

dxdt(1) = (1 + x(1)) * ( drag_f/(1 - e_f) + drag_l/(E - 1) );


% ------------------------------------------------------------
% 2) delta_lambda_dot
% ------------------------------------------------------------

dxdt(2) = -0.5*A * ( (2*a_f^2*x(1))/(1 + x(1))^2 + 7*J_star*sin(2*(i_f - x(5)))*x(5) );


% ------------------------------------------------------------
% 3) delta_e_x_dot
% ------------------------------------------------------------

dxdt(3) = -0.25*J_star*A*I*x(4) + drag_f*cos(omega_f) + (drag_l/E) * (x(3) - e_f*cos(omega_f));


% ------------------------------------------------------------
% 4) delta_e_y_dot
% ------------------------------------------------------------

dxdt(4) = 0.25*J_star*A*I*x(3) + drag_f*sin(omega_f) + (drag_l/E) * (x(4) - e_f*sin(omega_f));


% ------------------------------------------------------------
% 5) delta_i_x_dot
% ------------------------------------------------------------

dxdt(5) = 0;


% ------------------------------------------------------------
% 6) delta_i_y_dot
% ------------------------------------------------------------

dxdt(6) = J_star*A*sin(i_f - x(5))^2*x(5);

end


%% ============================================================
% Fanebust Eq. (3.13)-(3.14)
% ============================================================

function value = f_drag(e)

value = 1.61e4*e^0.02701 - 1.61e4;

end